#!/usr/bin/env bash
#
# Lock & rewrite detection guardrail (static, offline SQL inspection).
#
# This CI guardrail reads one or more Prisma migration SQL files (or directories
# of them) and flags DDL that would take a table-level ACCESS EXCLUSIVE lock
# and/or force a full-table rewrite — the hazard that halts IoT ingestion on a
# 2.1-billion-row, multi-terabyte (~2 TB) table. On a match it exits non-zero so
# the pipeline fails and a human reviews the plan.
#
# The canonical hazard it catches is the naive migration Prisma autogenerates
# when `sensor_readings.id` changes from Int to BigInt:
#     ALTER TABLE sensor_readings ALTER COLUMN id TYPE bigint;
# The zero-downtime fix is one of the human-reviewed candidate approaches (A–D),
# hand-authored as raw-SQL expand/contract Prisma migrations.
#
# SCOPE / CAPABILITY: this implements the STATIC pattern check only. It inspects
# the SQL text (no database, no network) and never executes it — file contents
# are treated as untrusted and are never eval'd. It does NOT connect to a
# database or probe pg_locks. The static check is sufficient to catch the
# rewrite-forcing DDL above and runs entirely offline in CI.
#
# Usage: detect_lock_rewrite.sh <path> [<path> ...]
#   <path>  a .sql migration file, or a directory searched recursively for
#           migration.sql / *.sql files.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "${HERE}/lib.sh"

[[ $# -ge 1 ]] || fail "usage: detect_lock_rewrite.sh <path> [<path> ...]"

# Collect SQL files from the provided paths (files and/or directories).
SQL_FILES=()
for path in "$@"; do
  if [[ -d "${path}" ]]; then
    while IFS= read -r -d '' f; do
      SQL_FILES+=("${f}")
    done < <(find "${path}" -type f -name '*.sql' -print0)
  elif [[ -f "${path}" ]]; then
    SQL_FILES+=("${path}")
  else
    fail "path not found: ${path}"
  fi
done

[[ ${#SQL_FILES[@]} -ge 1 ]] || fail "no SQL files found in: $*"

# inspect_sql <file> — static scan of a single SQL file. Flags rewrite-forcing /
# ACCESS EXCLUSIVE-on-hot-PK operations. Returns non-zero (via fail) on a hazard.
inspect_sql() {
  local file="$1"
  log "inspecting ${file}"

  # Normalize to a single line, collapse whitespace, lowercase — tolerates the
  # DDL being split across lines or spaced oddly. The content is only pattern-
  # matched, never executed.
  local sql
  sql="$(tr '\n' ' ' <"${file}" | tr -s '[:space:]' ' ' | tr '[:upper:]' '[:lower:]')"

  # 1. A raw column TYPE change is the classic full-table-rewrite trigger. The
  #    int->bigint widening of a hot/PK column (sensor_readings.id) is the
  #    centerpiece hazard.
  if printf '%s' "${sql}" | grep -Eq 'alter[[:space:]]+table[[:space:]]+.*alter[[:space:]]+(column[[:space:]]+)?[a-z0-9_."]+[[:space:]]+(set[[:space:]]+data[[:space:]]+)?type[[:space:]]'; then
    fail "${file}: ALTER COLUMN ... TYPE changes a column type -> full-table rewrite + ACCESS EXCLUSIVE lock (hours of halted ingestion on a 2.1B-row/~2 TB table). Do NOT ship the naive autogenerated migration; use a human-reviewed candidate approach (A-D: raw-SQL expand/contract, dual-write/swap, sequence stopgap, or hypertable)."
  fi

  # 2. Adding a NOT NULL column without a safe/constant default rewrites the
  #    table (every existing row must be updated under ACCESS EXCLUSIVE).
  if printf '%s' "${sql}" | grep -Eq 'alter[[:space:]]+table[[:space:]]+.*add[[:space:]]+(column[[:space:]]+)?[a-z0-9_."]+[^;]*not[[:space:]]+null'; then
    if ! printf '%s' "${sql}" | grep -Eq 'alter[[:space:]]+table[[:space:]]+.*add[[:space:]]+(column[[:space:]]+)?[a-z0-9_."]+[^;]*not[[:space:]]+null[^;]*default'; then
      fail "${file}: ADD COLUMN ... NOT NULL without a DEFAULT -> table rewrite / long lock. Add a constant default or use a human-reviewed candidate approach (A-D)."
    fi
  fi

  ok "${file}: no rewrite/lock hazard detected by static check"
}

for f in "${SQL_FILES[@]}"; do
  inspect_sql "${f}"
done

ok "all migrations passed the static lock/rewrite guardrail"
